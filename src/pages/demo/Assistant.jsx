import { useState } from "react";
import { Link } from "react-router-dom";
import { Bot, Database } from "lucide-react";
import { useDemo } from "../../lib/demoStore.jsx";
import { INTENTS, answer } from "../../lib/assistant.js";
import { PageTitle } from "./common.jsx";

export default function Assistant() {
  const d = useDemo();
  const [cid, setCid] = useState(d.visibleCandidates[0]?.id);
  const [log, setLog] = useState([]);
  const cand = d.visibleCandidates.find((c) => c.id === cid) || d.visibleCandidates[0];
  const intents = d.can.seeAll ? INTENTS : INTENTS.filter((i) => i.id !== "cohort");
  const ask = (intent) => {
    const r = answer(intent.id, { candidate: cand, candidates: d.visibleCandidates, attempts: d.attempts, targetFor: d.targetFor, hoursFor: d.hoursFor });
    setLog((l) => [...l, { q: intent.label, who: intent.id === "cohort" ? "Cohort" : cand.name, ...r }]);
  };
  return (
    <div className="max-w-3xl">
      <PageTitle title="Assistant" sub="Demo assistant · answers from sample data. Rule-based templates; no AI model is called." />
      <div className="card p-4">
        <label className="text-sm"><span className="label">Candidate</span><select className="input sm:!w-80" value={cand?.id} onChange={(e) => setCid(e.target.value)}>{d.visibleCandidates.map((c) => <option key={c.id} value={c.id}>{c.name} · {c.id}</option>)}</select></label>
        <div className="mt-4 flex flex-wrap gap-2">{intents.map((i) => <button key={i.id} className="btn btn-line btn-sm" onClick={() => ask(i)}>{i.label}</button>)}</div>
      </div>
      <div className="mt-5 space-y-4" aria-live="polite">
        {log.length === 0 && <p className="card p-8 text-center text-sm text-muted">Pick a question above. Each answer lists the sample records it used.</p>}
        {log.map((m, i) => (
          <div key={i} className="space-y-2">
            <p className="ml-auto w-fit max-w-[85%] rounded-2xl rounded-br-sm bg-indigo px-4 py-2.5 text-sm text-white">{m.q} <span className="opacity-70">({m.who})</span></p>
            <div className="max-w-[92%] rounded-2xl rounded-bl-sm border border-line bg-white p-4 text-sm">
              <p className="mb-2 flex items-center gap-1.5 font-mono text-[0.65rem] uppercase tracking-wider text-faint"><Bot className="size-3.5" />Demo assistant · answers from sample data</p>
              <p className="whitespace-pre-line leading-relaxed">{m.text}</p>
              <details className="mt-3 text-xs text-muted"><summary className="flex cursor-pointer items-center gap-1"><Database className="size-3.5" />Records used ({m.used.length})</summary><p className="mt-1 font-mono leading-relaxed">{m.used.join(", ") || "none"}</p></details>
            </div>
          </div>
        ))}
      </div>
      <p className="mt-6 text-xs text-faint">In production, explanations would be generated by Anthropic Claude on Amazon Bedrock, constrained to the candidate's recorded results and reviewed worked solutions (see <Link to="/technology" className="underline">Technology</Link>).</p>
    </div>
  );
}
